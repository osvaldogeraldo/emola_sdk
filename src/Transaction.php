<?php

namespace BrilliantMind\Sdk;

use BrilliantMind\Sdk\Contracts\TransactionContract;
use Exception;

/**
 * The response of a `c2b()` or `b2c()` call.
 *
 * The gateway answers in two levels:
 *
 * - **Gateway level** (`error`, `description`): `0` means the gateway accepted
 *   the call. Anything else (login failed, IP not allowed, function inactive...)
 *   means the request never reached the wallet, and `original` is usually empty
 *   or plain text.
 * - **Wallet level** (`original` -> `errorCode`, `message`, `reqeustId`): the
 *   business result. `0` is success; see the e-Mola specification for the rest
 *   (`11` customer did not enter PIN, `12` no e-Mola account, `14` transId
 *   already exists...).
 *
 * Parsing never throws on a malformed or non-XML `original`: the reason of a
 * gateway refusal is kept in `description()` / `text()` instead of being lost.
 */
class Transaction implements TransactionContract
{
    /**
     * The raw object returned by the SoapClient.
     *
     * @var object
     */
    protected object $attributes;

    /**
     * The parsed `original` envelope, when it is XML.
     *
     * @var \SimpleXMLElement|null
     */
    protected $xml = null;

    /**
     * The fields inside `<return>` of the `original` envelope.
     *
     * @var array<string, string>
     */
    protected array $return = [];

    /**
     * `original` content that is not XML (e.g. a gateway error text).
     */
    protected string $text = '';

    /**
     * Construct transaction from the eMola API response.
     *
     * @param object|string $response The SoapClient result, or the exception message when the call failed.
     * @throws Exception When the call itself failed (network, WSDL, SOAP fault).
     */
    public function __construct($response)
    {
        if (is_string($response)) {
            throw new Exception($response);
        }

        $this->attributes = $response;

        $original = trim((string) ($response->original ?? ''));

        // Some gateways send the envelope escaped (`&lt;S:Envelope`).
        if (strpos($original, '&lt;') === 0) {
            $original = trim(html_entity_decode($original, ENT_QUOTES | ENT_XML1, 'UTF-8'));
        }

        if ($original === '') {
            return;
        }

        if (strpos($original, '<') !== 0) {
            $this->text = $original;

            return;
        }

        $cleanXml = (string) preg_replace('/(<\/?)[\w.-]+:/', '$1', $original);

        $previous = libxml_use_internal_errors(true);

        try {
            $xml = simplexml_load_string($cleanXml, 'SimpleXMLElement', LIBXML_NOCDATA | LIBXML_NONET);
        } finally {
            libxml_clear_errors();
            libxml_use_internal_errors($previous);
        }

        if ($xml === false) {
            $this->text = $original;

            return;
        }

        $this->xml = $xml;

        foreach ($xml->xpath('//return/*') ?: [] as $field) {
            $this->return[$field->getName()] = trim((string) $field);
        }
    }

    /** Gateway error code (`0` = the gateway accepted the call). */
    public function gatewayError(): string
    {
        return trim((string) ($this->attributes->error ?? ''));
    }

    /** Gateway description of `gatewayError()`, when it sends one. */
    public function description(): ?string
    {
        $description = trim((string) ($this->attributes->description ?? ''));

        return $description === '' ? null : $description;
    }

    /** `original` content that was not XML (gateway error text), or `null`. */
    public function text(): ?string
    {
        return $this->text === '' ? null : $this->text;
    }

    /** Wallet (business) error code: `0` = success. `null` when the call never reached the wallet. */
    public function errorCode(): ?string
    {
        return isset($this->return['errorCode']) && $this->return['errorCode'] !== ''
            ? $this->return['errorCode']
            : null;
    }

    /** Wallet message for `errorCode()`. */
    public function message(): ?string
    {
        return $this->return['message'] ?? null;
    }

    /** Request id generated by e-Mola (the gateway spells it `reqeustId`). */
    public function requestId(): ?string
    {
        return $this->return['reqeustId'] ?? null;
    }

    /** Gateway transaction id. */
    public function gatewayTransactionId(): ?string
    {
        $id = trim((string) ($this->attributes->gwtransid ?? ''));

        return $id === '' ? null : $id;
    }

    /**
     * Every field of `<return>`, e.g. `orgResponseCode` in a status query or
     * `balance` in a balance query.
     *
     * @return array<string, string>
     */
    public function fields(): array
    {
        return $this->return;
    }

    /** True only when both the gateway and the wallet answered `0`. */
    public function successful(): bool
    {
        $gateway = $this->gatewayError();

        return ($gateway === '' || $gateway === '0') && $this->errorCode() === '0';
    }

    /**
     * Convert the model instance to an array.
     *
     * The keys of 1.0 are kept (`error`, `original.errorCode`,
     * `original.message`, `original.requestId`, `gwtransid`). Since 1.1
     * `error` is the real gateway code - 1.0 always returned `0` when there
     * was an envelope - and `description` / `text` carry the gateway reason.
     *
     * @return array
     */
    public function toArray(): array
    {
        $gateway = $this->gatewayError();

        return [
            'error' => $gateway === '' ? 0 : (ctype_digit($gateway) ? (int) $gateway : $gateway),
            'description' => $this->description(),
            'text' => $this->text(),
            'original' => $this->return === [] ? [] : [
                'errorCode' => $this->return['errorCode'] ?? null,
                'message' => $this->return['message'] ?? null,
                'requestId' => $this->return['reqeustId'] ?? null,
            ],
            'gwtransid' => $this->attributes->gwtransid ?? null,
        ];
    }
}
